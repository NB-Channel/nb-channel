🌱 扶植中小公司
新增「成长基金」：公司税的一半转给市值 1000 万以下的公司，越小的分得越多，每天最多发 1500 万
钱是从大公司手里收来的，不是凭空印的，不会让 NB币 贬值
市值低于 50 万的公司不再收公司税

🏦 公司税与垄断税
按市值分段征收，直接从公司市值扣除：30 万以下免征 · 30 万~100 万 0.2% · 100 万~2000 万 0.5% · 2000 万~5000 万 1% · 5000 万以上 2%
某家公司市值超过全站 40% 时额外加征 5%「垄断税」，回落到 40% 以下自动停征
每天休市后（北京时间 20:00 之后）结算一次

📱 手机扫码登录
电脑打开登录页点「📱 扫码」→ 手机 APP「扫一扫」扫一下 → 确认，电脑就登录好了，全程不传输密码
确认页会显示设备所在地区（如「中国 · 内蒙古 · 呼和浩特」），一眼看出是不是自己的电脑
⚠️ 不是你的电脑千万别点确认；别人发二维码让你扫，一律是盗号，直接点「取消」

📷 APP 1.0.6 新增「扫一扫」
