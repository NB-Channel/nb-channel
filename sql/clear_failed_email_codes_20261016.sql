-- ============================================================
--  救急：把被「发送失败」吃掉的验证码额度还回来
--
--  有人报：
--    「我邮箱都没收到消息就提示发送上限，发送失败也要被计数吗？
--      发送失败加发送过于频繁，然后一条没收到给我干上限了！！！」
--
--  ── 原因 ──
--  SCF 原来的顺序是【先计数、先写码、最后才发信】，
--  而发信失败时前两步都不回滚。
--  于是每失败一次：
--      · 内存限频 +1
--      · email_codes 里插一行（数据库那边有「同一邮箱每天最多 5 次」）
--  信一封没发出去，额度却被吃掉 5 次 → 当天这个邮箱就废了。
--
--  ✅ 代码已经改了（scf_mail_sender.py v6：先发信，成功了再写库）。
--     但已经写进库的那些「废码」还在，占了额度 —— 这个脚本把它们清掉。
--
--  ── 这个脚本做什么 ──
--  第 1 步  先看看现在库里有多少条、都是谁的（只查）
--  第 2 步  删掉【过期且没用过】的码 —— 这些是纯占额度的
--  第 3 步  单独把那位报问题的邮箱的记录清掉（让他今天就能再试）
--  第 4 步  验收
--
--  ⚠️ 只删「已经过期 或 从来没被用过的旧码」，
--     不动任何还在有效期内的码（万一有人正等着用它登录）。
--
--  幂等。用法：整段复制到 Supabase → SQL Editor → Run
-- ============================================================


-- ============================================================
-- 第 1 步（只查）：现在库里什么情况
-- ============================================================
-- 1.1 总量、有效期内的量
SELECT count(*)                                                          AS 总条数,
       count(*) FILTER (WHERE expires_at > now() AND used_at IS NULL)     AS 还有效,
       count(*) FILTER (WHERE expires_at <= now())                        AS 已过期,
       count(*) FILTER (WHERE used_at IS NOT NULL)                        AS 已用过
  FROM public.email_codes;

-- 1.2 今天被吃掉额度最多的邮箱（前 15 个）
SELECT email                                   AS 邮箱,
       count(*)                                AS 今日条数,
       count(*) FILTER (WHERE used_at IS NOT NULL) AS 已用过,
       min(created_at)                         AS 最早,
       max(created_at)                         AS 最晚
  FROM public.email_codes
 WHERE created_at > now() - interval '1 day'
 GROUP BY email
 ORDER BY 2 DESC
 LIMIT 15;


-- ============================================================
-- 第 2 步：清掉【过期 且 没用过】的废码
--   ⚠️ 只删这一种 —— 还在有效期内的一个不动。
-- ============================================================
DO $$
DECLARE
    v_n int;
BEGIN
    DELETE FROM public.email_codes
     WHERE expires_at <= now()
       AND used_at IS NULL;
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RAISE NOTICE '清掉过期未用的码：% 条', v_n;
END $$;


-- ============================================================
-- 第 3 步：把报问题那位今天的额度还回去
--   他的邮箱：leo_di2026@163.com
--   ⚠️ 只删【今天、没用过】的 —— 他一条都没收到，那些码本来就是废的
-- ============================================================
DO $$
DECLARE
    v_n int;
BEGIN
    DELETE FROM public.email_codes
     WHERE lower(email) = 'leo_di2026@163.com'
       AND used_at IS NULL
       AND created_at > now() - interval '1 day';
    GET DIAGNOSTICS v_n = ROW_COUNT;
    RAISE NOTICE '清掉该邮箱今天的废码：% 条（额度已还回）', v_n;
END $$;


-- ============================================================
-- 第 4 步：验收
-- ============================================================
SELECT email AS 邮箱, count(*) AS 今日剩余条数
  FROM public.email_codes
 WHERE created_at > now() - interval '1 day'
 GROUP BY email
 ORDER BY 2 DESC
 LIMIT 10;

-- 期望：上面那个邮箱不再出现在名单里（或者说 0 条）→ 他今天能重新收到码了


