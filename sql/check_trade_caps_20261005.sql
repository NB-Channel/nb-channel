-- ============================================================
--  确认交易限额到底还在不在
--
--  上一版验证查询是靠变量名（v_buy_pct / v_abs_cap）判断的，
--  但数据库里的函数可能压根没有这些变量 —— 那样会报假警报。
--  这个版本改成查【逻辑特征】，有没有那段代码一目了然。
--
--  用法：整段复制到 Supabase → SQL Editor → Run
-- ============================================================

SELECT
    -- 每日额度：函数里有没有调用统计函数、有没有那句报错
    (position('_company_daily_flow' in d) > 0)      AS "有每日统计函数",
    (position('达到每日上限' in d) > 0)              AS "有每日上限报错",
    (position('v_buy_pct' in d) > 0)                AS "有每日额度常量",

    -- 单笔上限：是老的 50% 还是放宽后的 100 倍
    (position('v_cash * 0.5' in d) > 0)             AS "单笔还是50%",
    (position('v_cash * 100' in d) > 0)             AS "单笔已放宽100倍",

    -- 报错文案是否已换成人话
    (position('多打了几位数字' in d) > 0)            AS "报错文案已改白话",

    -- 函数体有多长（对照用）
    length(d)                                        AS "函数源码字数"
FROM (
    SELECT pg_get_functiondef(p.oid) AS d
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' AND p.proname = '_orig_buy_stock'
    LIMIT 1
) x;


-- ------------------------------------------------------------
--  怎么读结果
--
--   「有每日统计函数」= false  且  「有每日上限报错」= false
--        → 每日额度根本不存在，本来就没挡人。✅ 不用管
--
--   「有每日统计函数」= true
--        → 每日额度确实在生效，那还需要再处理（把结果发我）
--
--   「单笔已放宽100倍」= true  且  「单笔还是50%」= false
--        → 单笔上限已经按预期放宽了。✅
--
--   「报错文案已改白话」= true
--        → 文案替换也生效了。✅
-- ------------------------------------------------------------
