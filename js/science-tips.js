    function mountHomeBox() {
        var exist = document.querySelector('.nb-tip-box');
        if (!exist) {
            exist = document.createElement('div');
            exist.className = 'nb-tip-box';
            var head0 = document.createElement('div');
            head0.className = 'nb-tip-head';
            head0.textContent = '小Tips：';
            var body0 = document.createElement('div');
            body0.appendChild(makeTag());
            body0.appendChild(makeText());
            body0.appendChild(makeNextBtn(exist));
            exist.appendChild(head0);
            exist.appendChild(body0);
            fill(exist);
        }
        var box = exist;
        box.className = 'nb-tip-box';
        // 位置策略（兼顾"放对地方"和"别把页面拖卡"）：
        //   ui-nav.js 是异步注入首页各个模块的，公告出现得比导航晚。
        //   所以【等公告出现】再插，插完就不再动。
        //   为了不无限等，3 秒内没等到就用兜底位置。
        //   ⚠️ 全程最多插两次（第一次兜底、第二次纠正到公告后面），
        //      不做反复挪动 —— 上次页面卡就是反复挪 DOM 造成的。
        if (box.parentNode && document.body.contains(box)) {
            fill(box);
            // 已经插过了：只有一种情况需要再动一次 ——
            // 之前用的是兜底位置，现在公告出现了，挪到公告后面去。
            if (box.dataset.nbAnchored !== 'ann') {
                var ann2 = document.querySelector('.announcement-bar')
                        || document.getElementById('announcementBar')
                        || document.querySelector('.beta-announce')
                        || document.getElementById('betaAnnounce');
                if (ann2 && ann2.parentNode && document.body.contains(ann2) &&
                    document.body.contains(ann2)) {
                    if (box.previousElementSibling !== ann2) {
                        ann2.parentNode.insertBefore(box, ann2.nextSibling);
                    }
                    box.dataset.nbAnchored = 'ann';
                    window.__nbAnchor = '公告之后';
                }
            }
            return true;
        }

        // 还没插过：直接插到公告后面
        // ⚠️ 之前这里写错了 —— 只是"等公告出现"设了个标记，然后继续走兜底，
        //    等于等到了也不用。现在改成：找到公告就插它后面。
        var annNow = document.querySelector('.announcement-bar')
                  || document.getElementById('announcementBar')
                  || document.querySelector('.beta-announce')
                  || document.getElementById('betaAnnounce');
        if (annNow && annNow.parentNode && document.body.contains(annNow)) {
            annNow.parentNode.insertBefore(box, annNow.nextSibling);
            fill(box);
            box.dataset.nbAnchored = 'ann';
            window.__nbAnchor = '公告之后';
            return true;
        }
        // 公告还没渲染出来 → 这一轮先不插，等下一轮
        window.__nbWaitCount = (window.__nbWaitCount || 0) + 1;
        if (window.__nbWaitCount < 5) return false;

        // 兜底：原始 HTML 里那张"友商链接"卡片之前
        var anchor = null;
        var cards = document.querySelectorAll('.home-card');
        for (var i2 = 0; i2 < cards.length; i2++) {
            var t = cards[i2].textContent || '';
            if (t.indexOf('友商') >= 0 || t.indexOf('虚拟公司的网站') >= 0) {
                anchor = { n: cards[i2], after: false };
                break;
            }
        }
        if (!anchor) {
            var sc = document.querySelector('.stats-container');
            if (sc && sc.parentNode) anchor = { n: sc, after: false };
        }
        if (!anchor) return false;

        // 已经在正确位置就不动，否则挪过去（首页内容是异步渲染的，
        // 第一次进来可能还找不到"友商"那张卡片，等 DOM 稳定后要能纠正）
        if (anchor.after) {
            if (box.previousElementSibling !== anchor.n) {
                anchor.n.parentNode.insertBefore(box, anchor.n.nextSibling);
            }
        } else {
            if (box.nextElementSibling !== anchor.n) {
                anchor.n.parentNode.insertBefore(box, anchor.n);
            }
        }
        fill(box);
        return true;
    }

